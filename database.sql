CREATE DATABASE IF NOT EXISTS khoahoc CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE khoahoc;

CREATE TABLE IF NOT EXISTS KHOA_HOC (
    MaKhoaHoc INT AUTO_INCREMENT PRIMARY KEY,
    TenKhoaHoc VARCHAR(100) NOT NULL,
    MoTa VARCHAR(255),
    HocPhiMacDinh DECIMAL(12,2) CHECK (HocPhiMacDinh >= 0),
    ThoiLuong INT CHECK (ThoiLuong > 0)
    );

CREATE TABLE IF NOT EXISTS GIAO_VIEN (
    MaGV INT AUTO_INCREMENT PRIMARY KEY,
    HoTen VARCHAR(100) NOT NULL,
    NgaySinh DATE,
    GioiTinh VARCHAR(10),
    DienThoai VARCHAR(15),
    Email VARCHAR(100),
    TrinhDo VARCHAR(100),
    NgayVaoLam DATE,
    TrangThai VARCHAR(20) DEFAULT 'Đang làm việc'
    );

CREATE TABLE IF NOT EXISTS LOP_HOC (
   MaLop INT AUTO_INCREMENT PRIMARY KEY,
   MaKhoaHoc INT NOT NULL,
   MaGV INT NOT NULL,
   TenLop VARCHAR(100) NOT NULL,
    NgayKhaiGiang DATE,
    NgayKetThuc DATE,
    SiSoToiDa INT CHECK (SiSoToiDa > 0),
    PhongHoc VARCHAR(30),
    TrangThai VARCHAR(20) DEFAULT 'Sắp khai giảng',
    FOREIGN KEY (MaKhoaHoc) REFERENCES KHOA_HOC(MaKhoaHoc) ON DELETE RESTRICT ON UPDATE CASCADE,
    FOREIGN KEY (MaGV) REFERENCES GIAO_VIEN(MaGV) ON DELETE RESTRICT ON UPDATE CASCADE
    );

CREATE TABLE IF NOT EXISTS HOC_VIEN (
    MaHV INT AUTO_INCREMENT PRIMARY KEY,
    HoTen VARCHAR(100) NOT NULL,
    NgaySinh DATE,
    GioiTinh VARCHAR(10),
    DienThoai VARCHAR(15),
    Email VARCHAR(100),
    DiaChi VARCHAR(100),
    TrangThai VARCHAR(20) DEFAULT 'Đang học'
    );

CREATE TABLE IF NOT EXISTS DANG_KY (
   MaHV INT NOT NULL,
   MaLop INT NOT NULL,
   NgayDK DATE DEFAULT (CURRENT_DATE),
    TrangThaiDK VARCHAR(20) DEFAULT 'Đã đăng ký',
    HocPhi DECIMAL(12,2) CHECK (HocPhi >= 0),
    PRIMARY KEY (MaHV, MaLop),
    FOREIGN KEY (MaHV) REFERENCES HOC_VIEN(MaHV) ON DELETE RESTRICT ON UPDATE CASCADE,
    FOREIGN KEY (MaLop) REFERENCES LOP_HOC(MaLop) ON DELETE RESTRICT ON UPDATE CASCADE
    );

CREATE TABLE IF NOT EXISTS PHIEU_THU (
     MaPT INT AUTO_INCREMENT PRIMARY KEY,
     MaHV INT NOT NULL,
     NgayThu DATETIME DEFAULT CURRENT_TIMESTAMP,
     SoTien DECIMAL(12,2) CHECK (SoTien > 0),
    PhuongThucTT VARCHAR(30),
    GhiChu VARCHAR(255),
    NguoiThu VARCHAR(100),
    FOREIGN KEY (MaHV) REFERENCES HOC_VIEN(MaHV) ON DELETE RESTRICT ON UPDATE CASCADE
    );